"""
A reader for SNOWPACK .pro files using the xarray library for efficiency.

This module provides a class, SnowpackProfile, for parsing, processing,
and analyzing data from .pro files generated by the SNOWPACK model. It is designed
to handle the specific format of these files, including metadata and layered
profile data for multiple timestamps.

The core data structure used is an xarray.Dataset, which allows for labeled,
multi-dimensional arrays that are ideal for scientific time-series data. This
approach enables highly efficient, vectorized computations, significantly
outperforming traditional row-by-row or profile-by-profile processing.

Key Features:
- Parses station metadata and time-series profile data from a .pro file upon
  initialization.
- Stores profile data in a multi-dimensional xarray.Dataset for highly
  efficient, vectorized processing.
- Automatically calculates the critical cut length for flat terrain (rc_flat) for
  all profiles in a single vectorized operation.
- Provides methods to convert individual profiles into pandas DataFrames for
  easy analysis.
- Includes a highly optimized, vectorized summary method to extract key statistics
  (min, max, mean, etc.) across all profiles.

Workflow:
1.  Instantiate the `SnowpackProfile` with the path to a .pro file. The data
    is read and processed into an xarray.Dataset immediately.
2.  Access metadata via the `.metadata` attribute and the core data via the
    `.data` (xarray.Dataset) attribute.
3.  Use methods like `list_timestamps()` or `profile_to_dataframe()` to access
    the parsed data.
4.  Use `get_profile_summary()` to generate a time-series DataFrame of summary
    statistics for specified snowpack parameters.

Dependencies:
- pandas
- numpy
- xarray
- tqdm

Last Updated: July 2nd, 2025
@author: Avalanche
"""
